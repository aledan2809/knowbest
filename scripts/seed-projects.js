async function seed() {
  console.log(`\n🌱 Seeding ${projects.length} projects with upsert...\n`);

  let created = 0;
  let updated = 0;

  for (const project of projects) {
    try {
      const result = await prisma.project.upsert({
        where: { slug: project.slug },
        update: {
          name: project.name,
          nameEn: project.nameEn,
          description: project.description,
          descriptionEn: project.descriptionEn,
          category: project.category,
          status: project.status,
          demoUrl: project.demoUrl || null,
          prodUrl: project.prodUrl || null,
          standalone: project.standalone ?? false,
          icon: project.icon,
          techStack: project.techStack || [],
          tags: project.tags || [],
          featured: project.featured || false,
          sortOrder: project.sortOrder,
          visible: true,
          pricingType: "FREE",
          accessType: "PUBLIC",
        },
        create: {
          name: project.name,
          nameEn: project.nameEn,
          slug: project.slug,
          description: project.description,
          descriptionEn: project.descriptionEn,
          category: project.category,
          status: project.status,
          demoUrl: project.demoUrl || null,
          prodUrl: project.prodUrl || null,
          standalone: project.standalone ?? false,
          icon: project.icon,
          techStack: project.techStack || [],
          tags: project.tags || [],
          featured: project.featured || false,
          sortOrder: project.sortOrder,
          visible: true,
          pricingType: "FREE",
          accessType: "PUBLIC",
        },
      });

      // Check if created (newly inserted) or updated
      // Prisma upsert doesn't directly tell us, but we can check createdAt vs updatedAt
      const isNew = result.createdAt.getTime() === result.updatedAt.getTime();
      if (isNew) {
        created++;
        console.log(`✅ Created: ${project.name}`);
      } else {
        updated++;
        console.log(`🔄 Updated: ${project.name}`);
      }
    } catch (e) {
      console.log(`❌ ${project.name}: ${e.message}`);
    }
  }

  console.log(`\n✅ Done! Created: ${created}, Updated: ${updated}, Total: ${projects.length}\n`);

  await prisma.$disconnect();
}

seed().catch((e) => {
  console.error(e);
  prisma.$disconnect();
  process.exit(1);
});
